#!/usr/bin/env python3
"""
Build static language pages from the Korean source page.

  index.html (KO, source of truth)  +  i18n/strings.json (EN/JA)
      -> en/index.html, ja/index.html

Usage (from the repo root, Python 3.8+, no extra packages):
    python tools/build_i18n.py

Rules
- Elements with data-i18n="key"       : inner HTML is replaced with strings[lang][key]
- Elements with data-i18n-attr="a:k;b:k2" : attribute a gets strings[lang][k], ...
- Relative URLs (assets/, css/, js/, favicon) in src/srcset/href/content are prefixed with "../"
- <html lang>, canonical, og:url and the KO/EN/JA switcher are rewritten per language
Missing keys are reported and fall back to the Korean text.
"""
import html
import json
import re
import sys
from html.parser import HTMLParser
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BASE_URL = "https://greenbraird.github.io/SproutStudioWeb/"
LANGS = {"en": "en/", "ja": "ja/"}
VOID = {"area", "base", "br", "col", "embed", "hr", "img", "input", "link", "meta", "source", "track", "wbr"}


class Locator(HTMLParser):
    """Find [start, end) offsets of the inner HTML of every element carrying data-i18n."""

    def __init__(self, text):
        super().__init__(convert_charrefs=False)
        self.text = text
        self.line_starts = [0]
        for m in re.finditer("\n", text):
            self.line_starts.append(m.end())
        self.stack = []
        self.found = []  # (inner_start, inner_end, key)

    def _offset(self):
        line, col = self.getpos()
        return self.line_starts[line - 1] + col

    def handle_starttag(self, tag, attrs):
        start = self._offset()
        end = start + len(self.get_starttag_text())
        if tag in VOID:
            return
        key = dict(attrs).get("data-i18n")
        self.stack.append((tag, end, key))

    def handle_startendtag(self, tag, attrs):
        pass

    def handle_endtag(self, tag):
        pos = self._offset()
        while self.stack:
            t, inner_start, key = self.stack.pop()
            if t == tag:
                if key:
                    self.found.append((inner_start, pos, key))
                break


def translate(src, lang, strings, missing):
    pack = strings.get(lang, {})
    loc = Locator(src)
    loc.feed(src)
    loc.close()
    out = src
    for inner_start, inner_end, key in sorted(loc.found, key=lambda x: -x[0]):
        if key in pack:
            out = out[:inner_start] + pack[key] + out[inner_end:]
        else:
            missing.add(key)

    def attr_sub(m):
        tag = m.group(0)
        spec = re.search(r'data-i18n-attr="([^"]*)"', tag).group(1)
        for pair in spec.split(";"):
            if ":" not in pair:
                continue
            attr, key = [p.strip() for p in pair.split(":", 1)]
            if key not in pack:
                missing.add(key)
                continue
            val = html.escape(pack[key], quote=True)
            new, n = re.subn(r'(\s%s=")[^"]*(")' % re.escape(attr), lambda mm: mm.group(1) + val + mm.group(2), tag)
            tag = new if n else tag.replace(" data-i18n-attr=", ' %s="%s" data-i18n-attr=' % (attr, val), 1)
        return tag

    out = re.sub(r"<[a-zA-Z][^<>]*data-i18n-attr=\"[^\"]*\"[^<>]*>", attr_sub, out)
    return out


def relocate(page, lang):
    # html lang
    page = re.sub(r'<html lang="ko" data-lang="ko">', '<html lang="%s" data-lang="%s">' % (lang, lang), page, count=1)
    # relative asset URLs -> ../
    page = re.sub(r'((?:src|srcset|href|content)=")(?=(?:assets/|css/|js/|favicon))', r"\1../", page)
    # self URLs (canonical, og:url)
    self_url = BASE_URL + LANGS[lang]
    page = re.sub(r'(<link rel="canonical" data-self-url href=")[^"]*(")', r"\g<1>%s\2" % self_url, page)
    page = re.sub(r'(<meta property="og:url" data-self-url content=")[^"]*(")', r"\g<1>%s\2" % self_url, page)
    # language switcher
    hrefs = {"ko": "../", "en": "../en/", "ja": "../ja/"}
    hrefs[lang] = "./"

    def sw(m):
        code = m.group(2)
        tag = re.sub(r'href="[^"]*"', 'href="%s"' % hrefs[code], m.group(0))
        tag = tag.replace(' aria-current="page"', "")
        if code == lang:
            tag = tag.replace(">", ' aria-current="page">', 1) if tag.endswith(">") else tag
        return tag

    page = re.sub(r'(<a class="lang-link" data-lang-link="(ko|en|ja)"[^>]*>)', sw, page)
    return page


def main():
    src = (ROOT / "index.html").read_text(encoding="utf-8")
    strings = json.loads((ROOT / "i18n" / "strings.json").read_text(encoding="utf-8"))
    ok = True
    for lang, sub in LANGS.items():
        missing = set()
        page = translate(src, lang, strings, missing)
        page = relocate(page, lang)
        page = page.replace(
            "<!DOCTYPE html>",
            "<!DOCTYPE html>\n<!-- GENERATED by tools/build_i18n.py from index.html + i18n/strings.json. Do not edit by hand. -->",
            1,
        )
        dest = ROOT / sub / "index.html"
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(page, encoding="utf-8")
        print("wrote", dest.relative_to(ROOT), "(missing keys: %s)" % (", ".join(sorted(missing)) or "none"))
        if missing:
            ok = False
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
